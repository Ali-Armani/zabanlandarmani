export const faNumber = (n: number) => n.toLocaleString("fa-IR");
export function normalizeAnswer(value: string) {
  return value
    .toLowerCase()
    .replace(/[’‘]/g, "'")
    .replace(/[.,!?—]/g, "")
    .replace(/\s+/g, " ")
    .trim();
}
export function placementLevel(correct: number, total: number) {
  return correct / total >= 0.8 ? "A1-ready" : "A1";
}
